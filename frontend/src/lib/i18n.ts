const dicts: Record<Lang, Dict> = { en, es };
let lang: Lang = "en"; // always English until the driver switches
const subs = new Set<(l: Lang) => void>();
storage.getItem(LANG_KEY).then((v) => { if (v === "es" || v === "en") { lang = v; subs.forEach((f) => f(lang)); } });

export function getLang() { return lang; }
export async function setLang(l: Lang) { lang = l; await storage.setItem(LANG_KEY, l); subs.forEach((f) => f(l)); }

/** Plain (non-hook) lookup, e.g. for the background notification text. */
export function t<K extends keyof Dict>(k: K): Dict[K] { return dicts[lang][k]; }

export function useI18n() {
  const [l, setL] = useState<Lang>(lang);
  useEffect(() => { const f = (x: Lang) => setL(x); subs.add(f); setL(lang); return () => { subs.delete(f); }; }, []);
  return { lang: l, t: dicts[l], setLang };
}
